        "        for idx in ranked_indices:\n"
        "            chunk = list(self.dual_index.chunks_lookup.values())[idx]\n"
        "            if chunk.tenant_id == tenant_id and scores[idx] > 0.0:\n"
        "                filtered_ids.append(chunk.chunk_id)\n"
        "            if len(filtered_ids) >= top_k:\n"
        "                break\n"
        "        return filtered_ids\n"
        "\n"
        "    def hybrid_search(self, query: str, tenant_id: str, top_k: int = 3) -> List[Dict[str, Any]]:\n"
        "        dense_ids = self.search_dense(query, tenant_id=tenant_id, top_k=10)\n"
        "        sparse_ids = self.search_sparse(query, tenant_id=tenant_id, top_k=10)\n"
        "        \n"
        "        # Calculate RRF scores\n"
        "        rrf_scores = {}\n"
        "        for rank, cid in enumerate(dense_ids, start=1):\n"
        "            rrf_scores[cid] = rrf_scores.get(cid, 0.0) + (1.0 / (self.rrf_k + rank))\n"
        "            \n"
        "        for rank, cid in enumerate(sparse_ids, start=1):\n"
        "            rrf_scores[cid] = rrf_scores.get(cid, 0.0) + (1.0 / (self.rrf_k + rank))\n"
        "            \n"
        "        ranked_candidates = sorted(rrf_scores.items(), key=lambda x: x[1], reverse=True)[:top_k]\n"
        "        \n"
        "        results = []\n"
        "        for rank, (cid, score) in enumerate(ranked_candidates, start=1):\n"
        "            chunk = self.dual_index.chunks_lookup[cid]\n"
        "            results.append({\n"
        "                'rank': rank,\n"
        "                'chunk_id': cid,\n"
        "                'score': score,\n"
        "                'dense_rank': (dense_ids.index(cid) + 1) if cid in dense_ids else None,\n"
        "                'sparse_rank': (sparse_ids.index(cid) + 1) if cid in sparse_ids else None,\n"
        "                'text': chunk.text,\n"
        "                'title': chunk.parent_title\n"
        "            })\n"
        "        return results\n"
        "\n"
        "retriever = HybridRetriever(dual_index)\n"
        "\n"
        "# Test query with both semantic intent and an exact error code\n"
        "test_query = 'What is the remediation procedure for error code ERR_AUTH_504?'\n"
        "fused_results = retriever.hybrid_search(test_query, tenant_id='tenant_enterprise', top_k=3)\n"
        "\n"
        "print(f\"Hybrid Search Results for query: '{test_query}'\")\n"
        "for r in fused_results:\n"
        "    print(f\"Rank #{r['rank']} | Score: {r['score']:.4f} | Dense Rank: {r['dense_rank']} | Sparse Rank: {r['sparse_rank']}\")\n"
        "    print(f\"  Snippet [{r['chunk_id']}]: {r['text'][:90]}...\\n\")"
