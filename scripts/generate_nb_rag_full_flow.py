        "                    messages=[{'role': 'user', 'content': prompt}],\n"
        "                    temperature=0.1\n"
        "                )\n"
        "                return {'provider': 'Groq (llama-3.1-8b)', 'text': completion.choices[0].message.content, 'prompt': prompt}\n"
        "            except Exception as e:\n"
        "                print(f'Groq call failed ({e}), falling back...')\n"
        "                \n"
        "        # 2. Try Gemini (if key present)\n"
        "        if self.gemini_key:\n"
        "            try:\n"
        "                from google import genai\n"
        "                client = genai.Client(api_key=self.gemini_key)\n"
        "                response = client.models.generate_content(\n"
        "                    model='gemini-2.5-flash',\n"
        "                    contents=prompt\n"
        "                )\n"
        "                return {'provider': 'Google Gemini (gemini-2.5-flash)', 'text': response.text, 'prompt': prompt}\n"
