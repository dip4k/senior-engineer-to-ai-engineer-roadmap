        "        context_xml = '<verified_context>\\n'\n"
        "        for c in retrieved_chunks:\n"
        "            context_xml += f\"  <document_chunk id='{c['chunk_id']}' source='{c['title']}'>\\n\"\n"
        "            context_xml += f\"    {c['text']}\\n\"\n"
        "            context_xml += f\"  </document_chunk>\\n\"\n"
        "        context_xml += '</verified_context>'\n"
        "        \n"
        "        prompt = (\n"
        "            f\"You are an enterprise AI assistant. Answer the user query using ONLY the verified context below.\\n\"\n"
        "            f\"Do not make up facts or extrapolate beyond what is stated. Cite the source chunk id for every claim using [chunk_id].\\n\"\n"
        "            f\"If the context does not contain the answer, state that you do not have sufficient information.\\n\\n\"\n"
        "            f\"{context_xml}\\n\\n\"\n"
        "            f\"User Query: {query}\\n\\n\"\n"
