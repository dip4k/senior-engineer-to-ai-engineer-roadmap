        "# %% [Ingestion] Hierarchical Chunking and Contextual Enrichment\n"
        "class DocumentChunk(BaseModel):\n"
        "    chunk_id: str\n"
        "    parent_doc_id: str\n"
        "    parent_title: str\n"
        "    tenant_id: str\n"
