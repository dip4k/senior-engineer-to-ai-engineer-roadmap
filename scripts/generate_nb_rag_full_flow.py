    nb.add_code(
        "# %% [Evaluation] Citation Audit and Hallucination Interceptor\n"
        "class CitationAuditBouncer:\n"
        "    @staticmethod\n"
        "    def audit_response(response_text: str, valid_chunk_ids: List[str]) -> Dict[str, Any]:\n"
        "        cited_ids = re.findall(r'\\[([a-zA-Z0-9_-]+)\\]', response_text)\n"
        "        valid_set = set(valid_chunk_ids)\n"
        "        \n"
        "        hallucinated_citations = [cid for cid in cited_ids if cid not in valid_set]\n"
        "        is_grounded = len(cited_ids) > 0 and len(hallucinated_citations) == 0\n"
        "        \n"
        "        return {\n"
        "            'is_grounded': is_grounded,\n"
        "            'total_citations': len(cited_ids),\n"
        "            'valid_citations': [cid for cid in cited_ids if cid in valid_set],\n"
        "            'hallucinated_citations': hallucinated_citations,\n"
        "            'verdict': 'PASSED (Grounded)' if is_grounded else 'FAILED (Ungrounded/Hallucinated)'\n"
        "        }\n"
        "\n"
        "audit = CitationAuditBouncer.audit_response(\n"
        "    generation_result['text'],\n"
        "    valid_chunk_ids=[c['chunk_id'] for c in fused_results]\n"
        ")\n"
        "\n"
        "print('--- Citation Bouncer Audit Report ---')\n"
        "for k, v in audit.items():\n"
        "    print(f\"{k:25s}: {v}\")"
    )

