        "            f\"The remediation procedure requires checking idempotency cache ID-KEY-99 before resubmission and waiting 300 seconds for automated webhook callback if status is PENDING [{retrieved_chunks[0]['chunk_id']}]. \"\n"
        "            f\"If it fails three consecutive times, escalate to DevOps at #sre-payments, and never re-charge the user credit card before clearing the lock [{retrieved_chunks[0]['chunk_id']}].\"\n"
        "        )\n"
        "        return {'provider': 'Deterministic Offline Generator', 'text': synthesized, 'prompt': prompt}\n"
        "\n"
        "generator = GroundedGenerator()\n"
        "generation_result = generator.generate_answer(test_query, fused_results)\n"
        "\n"
        "print(f\"--- Generated Augmented AI Result (Provider: {generation_result['provider']}) ---\")\n"
        "print(generation_result['text'])"
