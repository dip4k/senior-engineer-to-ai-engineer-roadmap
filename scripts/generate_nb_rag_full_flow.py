        "# %% [Retrieval] Hybrid Search and Reciprocal Rank Fusion Engine\n"
        "class HybridRetriever:\n"
        "    def __init__(self, dual_index: ProductionDualIndex, rrf_k: int = 60):\n"
        "        self.dual_index = dual_index\n"
        "        self.rrf_k = rrf_k\n"
        "\n"
