        "\n"
        "        if parent:\n"
        "            parent.children.append(span)\n"
        "        else:\n"
        "            self.root_spans.append(span)\n"
        "\n"
        "        self._span_stack.append(span)\n"
        "        return span\n"
        "\n"
        "    def end_span(self, span: GenAISpan, explicit_end_time: Optional[float] = None) -> None:\n"
