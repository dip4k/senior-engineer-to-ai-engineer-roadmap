        "        self._span_stack: List[GenAISpan] = []\n"
        "        self._current_trace_id: Optional[str] = None\n"
        "\n"
        "    def start_span(\n"
        "        self,\n"
        "        name: str,\n"
        "        attributes: Optional[Dict[str, Any]] = None,\n"
